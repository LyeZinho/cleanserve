use super::manifest::StackServiceDef;

pub fn render(project_slug: &str, services: &[(&str, &StackServiceDef)]) -> String {
    let mut out = String::new();
    out.push_str("# Generated by CleanServe — do not edit manually\n");
    out.push_str("name: cleanserve-");
    out.push_str(project_slug);
    out.push_str("\n\nservices:\n");

    let mut volume_names: Vec<String> = Vec::new();

    for (name, def) in services {
        out.push_str(&format!("  {}:\n", name));
        out.push_str(&format!("    image: {}\n", def.image));
        out.push_str("    restart: unless-stopped\n");
        out.push_str("    labels:\n");
        out.push_str("      com.cleanserve.managed: \"true\"\n");
        out.push_str(&format!("      com.cleanserve.project: \"{}\"\n", project_slug));
        out.push_str(&format!("      com.cleanserve.service: \"{}\"\n", name));

        if !def.environment.is_empty() {
            out.push_str("    environment:\n");
            for (k, v) in &def.environment {
                out.push_str(&format!("      {}: \"{}\"\n", k, escape_yaml(v)));
            }
        }

        if !def.ports.is_empty() {
            out.push_str("    ports:\n");
            for p in &def.ports {
                out.push_str(&format!(
                    "      - \"127.0.0.1:{}:{}\"\n",
                    p.host, p.container
                ));
            }
        }

        if !def.volumes.is_empty() {
            out.push_str("    volumes:\n");
            for mount in &def.volumes {
                let vol = format!("cleanserve-{}-{}-data", project_slug, name);
                volume_names.push(vol.clone());
                out.push_str(&format!("      - {}:{}\n", vol, mount));
            }
        }

        if *name == "phpmyadmin" {
            out.push_str("    depends_on:\n      - mysql\n");
        }

        out.push('\n');
    }

    if !volume_names.is_empty() {
        out.push_str("volumes:\n");
        for vol in volume_names {
            out.push_str(&format!("  {}:\n", vol));
        }
    }

    out
}

fn escape_yaml(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}
