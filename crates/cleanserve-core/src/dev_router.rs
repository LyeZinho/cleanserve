//! PHP built-in server router script (avoids double render when index.php is the router).

use std::path::{Path, PathBuf};

const ROUTER_FILENAME: &str = "router.php";

pub fn cleanserve_router_path(project_root: &Path) -> PathBuf {
    project_root.join(".cleanserve").join(ROUTER_FILENAME)
}

/// Write `.cleanserve/router.php` so `/index.php` is not used as the CLI router script.
pub fn ensure_dev_router(project_root: &Path, document_root: &Path) -> std::io::Result<PathBuf> {
    let index = document_root.join("index.php");
    if !index.exists() {
        return Ok(cleanserve_router_path(project_root));
    }

    let router_path = cleanserve_router_path(project_root);
    if let Some(parent) = router_path.parent() {
        std::fs::create_dir_all(parent)?;
    }

    let doc_root = document_root
        .canonicalize()
        .unwrap_or_else(|_| document_root.to_path_buf());
    let doc_root_escaped = doc_root.to_string_lossy().replace('\\', "\\\\");

    let body = format!(
        r#"<?php
declare(strict_types=1);
/**
 * Generated by CleanServe — do not edit manually.
 * Using index.php as the PHP `-S` router causes /index.php requests to run the app twice.
 */
$docRoot = '{doc_root}';
$uriPath = parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?: '/';
$fullPath = $docRoot . $uriPath;

// Serve static assets directly
if ($uriPath !== '/' && is_file($fullPath) && !preg_match('/\.php$/i', $uriPath)) {{
    return false;
}}

$index = $docRoot . '/index.php';

// Other existing PHP scripts (e.g. info.php) — let the built-in server handle them once
if ($uriPath !== '/' && is_file($fullPath) && realpath($fullPath) !== realpath($index)) {{
    return false;
}}

require $index;
"#,
        doc_root = doc_root_escaped
    );

    std::fs::write(&router_path, body)?;
    Ok(router_path)
}
